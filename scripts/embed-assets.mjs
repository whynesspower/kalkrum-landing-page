#!/usr/bin/env node
/**
 * Writes into lib/generated/ the files that pages need but cannot read from disk when they are served.
 *
 *   node scripts/embed-assets.mjs          write the modules
 *   node scripts/embed-assets.mjs --check  exit 1 if a module on disk is out of date
 *
 * Some hosts serve a build without the project folder: a page rendered there that reads content/notes/*.md or an
 * image with node:fs finds nothing. So the Markdown notes and the social-card mark are compiled into modules, and
 * the pages import those. `npm run dev` and `npm run build` run this first.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "lib/generated");
const check = process.argv.includes("--check");

const banner = (from) => `// Generated by scripts/embed-assets.mjs from ${from}. Do not edit: run \`npm run embed\`.\n`;

const notesDir = join(root, "content/notes");
const notes = readdirSync(notesDir)
  .filter((f) => f.endsWith(".md"))
  .sort();
const notesModule =
  banner("content/notes/*.md") +
  "\n/** The source of every Markdown note, by file name without its extension. */\n" +
  "export const noteSources: Record<string, string> = {\n" +
  notes
    .map(
      (f) =>
        `  ${JSON.stringify(f.replace(/\.md$/, ""))}: ${JSON.stringify(readFileSync(join(notesDir, f), "utf8"))},\n`,
    )
    .join("") +
  "};\n";

const markFile = "public/static/brand/kalkram-mark-192.png";
const markModule =
  banner(markFile) +
  "\n/** The KalKram mark for the social cards, as a PNG data URL. */\n" +
  `export const markPng =\n  ${JSON.stringify(`data:image/png;base64,${readFileSync(join(root, markFile)).toString("base64")}`)};\n`;

const files = { "notes.ts": notesModule, "mark.ts": markModule };
let stale = 0;
for (const [name, text] of Object.entries(files)) {
  const file = join(out, name);
  let current = null;
  try {
    current = readFileSync(file, "utf8");
  } catch {}
  if (current === text) continue;
  stale++;
  if (check) console.error(`lib/generated/${name} is out of date: run \`npm run embed\``);
  else {
    mkdirSync(out, { recursive: true });
    writeFileSync(file, text);
    console.log(`wrote lib/generated/${name}`);
  }
}
if (check && stale) process.exit(1);
if (!stale) console.log(`lib/generated is up to date (${notes.length} notes, 1 mark)`);
